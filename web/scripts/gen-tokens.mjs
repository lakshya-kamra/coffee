// Generates src/design/tokens.gen.css from the Android palette (ui/theme/Color.kt), so the web
// app's colours are the phone's colours, not a hand copy that drifts. Run: npm run tokens.
// src/design/tokens.test.ts regenerates in memory and fails when the committed CSS differs.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const COLOR_KT_RELATIVE = "../app/src/main/java/com/laksh/coffee/ui/theme/Color.kt";

const MOODS = ["idle", "bloom", "pouring", "steeping", "drawdown", "done"];

/** surface1 → surface1, inkHigh → ink-high, ringLiquid → ring-liquid. */
export function kebab(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

/** 0xAARRGGBB → "#RRGGBB" when opaque, else "rgb(R G B / a)" with a to 3 dp. */
export function argbToCss(hex8) {
  const v = hex8.toUpperCase();
  const a = parseInt(v.slice(0, 2), 16);
  const rgb = v.slice(2);
  if (a === 255) return "#" + rgb;
  const r = parseInt(rgb.slice(0, 2), 16);
  const g = parseInt(rgb.slice(2, 4), 16);
  const b = parseInt(rgb.slice(4, 6), 16);
  const alpha = String(Number((a / 255).toFixed(3)));
  return `rgb(${r} ${g} ${b} / ${alpha})`;
}

function block(src, startPattern) {
  const start = src.search(startPattern);
  if (start < 0) throw new Error(`Color.kt: ${startPattern} not found`);
  // Blocks end at the first line that is just ")" (data class instance or listOf).
  const end = src.indexOf("\n)", start);
  if (end < 0) throw new Error(`Color.kt: end of ${startPattern} not found`);
  return src.slice(start, end);
}

function palette(src, name) {
  const body = block(src, new RegExp(`val ${name} = CoffeeColors\\(`));
  const out = [];
  const re = /^\s*(\w+) = (?:Color\(0x([0-9A-Fa-f]{8})\)|Color\.Transparent)/gm;
  let m;
  while ((m = re.exec(body))) {
    out.push([kebab(m[1]), m[2] ? argbToCss(m[2]) : "transparent"]);
  }
  if (out.length === 0) throw new Error(`Color.kt: no colours in ${name}`);
  return out;
}

function moods(src, name) {
  const body = block(src, new RegExp(`val ${name} = listOf\\(`));
  const re = /MoodColors\(Color\(0x([0-9A-Fa-f]{8})\), Color\(0x([0-9A-Fa-f]{8})\), Color\(0x([0-9A-Fa-f]{8})\)\)/g;
  const out = [];
  let m;
  let i = 0;
  while ((m = re.exec(body))) {
    const mood = MOODS[i++];
    if (!mood) throw new Error(`Color.kt: more ${name} entries than BrewMood values`);
    out.push([`mood-${mood}-a`, argbToCss(m[1])], [`mood-${mood}-b`, argbToCss(m[2])], [`mood-${mood}-base`, argbToCss(m[3])]);
  }
  if (i !== MOODS.length) throw new Error(`Color.kt: ${name} has ${i} entries, expected ${MOODS.length}`);
  return out;
}

function rule(selector, pairs) {
  return `${selector} {\n${pairs.map(([k, v]) => `  --${k}: ${v};`).join("\n")}\n}\n`;
}

/** The whole tokens.gen.css text for a Color.kt source. Pure, so the parity test can call it. */
export function generateTokensCss(colorKt) {
  const src = colorKt.replace(/\r\n/g, "\n");
  return [
    "/* GENERATED by web/scripts/gen-tokens.mjs from app/.../ui/theme/Color.kt. Do not edit; run `npm run tokens`. */\n",
    rule(':root[data-theme="dark"]', palette(src, "DarkCoffee")),
    rule(':root[data-theme="light"]', palette(src, "LightCoffee")),
    rule(':root[data-theme="dark"]', moods(src, "DarkMoods")),
    rule(':root[data-theme="light"]', moods(src, "LightMoods")),
  ].join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const colorKt = path.resolve(webDir, COLOR_KT_RELATIVE);
  if (!existsSync(colorKt)) {
    console.error(`Color.kt not found at ${colorKt}; tokens.gen.css left as it is.`);
    process.exit(1);
  }
  const css = generateTokensCss(readFileSync(colorKt, "utf8"));
  const out = path.join(webDir, "src/design/tokens.gen.css");
  writeFileSync(out, css);
  console.log(`Wrote ${path.relative(webDir, out)}`);
}
